// Package docgen renders the checked-in command inventory for humans.
package docgen

import (
	"bytes"
	"fmt"
	"sort"
	"strings"

	"github.com/AmadeusDE/Misa/internal/inventory"
)

// Render returns the deterministic Markdown representation of inv.
func Render(inv *inventory.Inventory) []byte {
	var b bytes.Buffer
	b.WriteString("# Command inventory\n\n")
	b.WriteString("<!-- Generated by go run ./internal/inventory/gen; DO NOT EDIT. -->\n\n")
	b.WriteString("This inventory records registered commands and their provenance. Capability `unaudited` means behavior has not yet been audited; it is not a compatibility claim. Build constraints describe when a command is registered.\n\n")
	b.WriteString("## Commands\n\n| Name | Kind | Alias of | Sources | Build | Capability | Provenance | Tests |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n")
	commands := append([]inventory.Command(nil), inv.Commands...)
	sort.Slice(commands, func(i, j int) bool { return commands[i].Name < commands[j].Name })
	for _, c := range commands {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s |\n", cell(c.Name), cell(c.Kind), cell(c.AliasOf), list(c.Sources), cell(c.Build), cell(c.Capability), cell(c.Provenance), list(c.Tests))
	}
	b.WriteString("\n## UI-only entries\n\nThese entries are exposed through the UI rather than the builtin command registry.\n\n| Name | Sources |\n| --- | --- |\n")
	ui := append([]inventory.UIOnly(nil), inv.UIOnly...)
	sort.Slice(ui, func(i, j int) bool { return ui[i].Name < ui[j].Name })
	for _, entry := range ui {
		fmt.Fprintf(&b, "| %s | %s |\n", cell(entry.Name), list(entry.Sources))
	}
	b.WriteString("\n## Upstream sources\n\n| Name | URL | Revision | License | Status | Notes |\n| --- | --- | --- | --- | --- | --- |\n")
	sources := append([]inventory.Source(nil), inv.Sources...)
	sort.Slice(sources, func(i, j int) bool { return sources[i].Name < sources[j].Name })
	for _, source := range sources {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", cell(source.Name), cell(source.URL), cell(source.Revision), cell(source.License), cell(source.Status), cell(source.Notes))
	}
	return b.Bytes()
}

// cell escapes Markdown table delimiters and line breaks, including in build
// constraints (which commonly contain ||).
func cell(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "\r\n", "\n")
	s = strings.ReplaceAll(s, "\n", "<br>")
	return strings.ReplaceAll(s, "\r", "<br>")
}

func list(items []string) string {
	parts := make([]string, len(items))
	for i, item := range items {
		parts[i] = cell(item)
	}
	return strings.Join(parts, "<br>")
}
